"""Fabric Gradle-project template builders.

All version strings come from the game profile (``gameprofiles.json``); nothing
here hardcodes a Minecraft/Loom/Fabric version.  The emitted project is the
standard Fabric Loom shape and builds with ``gradle build`` against the real
26.2 dependency set.
"""
from __future__ import annotations

import json

from ...registry.gameprofile import GameProfile


def normalize_java_identifier(modid: str) -> str:
    """Turn a DSL modid into a legal Java package identifier (lowercase)."""
    return "".join(c if c.isalnum() else "_" for c in modid).lower() or "mod"


def package_name(modid: str) -> str:
    return f"net.pymod.{normalize_java_identifier(modid)}"


def main_class_name(modid: str) -> str:
    ident = normalize_java_identifier(modid)
    return "".join(p.capitalize() for p in ident.split("_")) + "Mod"


def settings_gradle(profile: GameProfile) -> str:
    return f"""\
pluginManagement {{
    repositories {{
        maven {{ url = uri("https://maven.fabricmc.net/") }}
        mavenCentral()
        gradlePluginPortal()
    }}
}}
"""


def gradle_properties() -> str:
    return """\
# generated by pymod
org.gradle.jvmargs=-Xmx2G
org.gradle.parallel=true
"""


def identity_mappings() -> str:
    """A tiny-v2 mapping with official -> intermediary -> named all identical.

    26.x ships a named (de-obfuscated) jar, and Fabric's published intermediary
    for 26.x is already an empty identity map.  Loom additionally requires a
    'named' column for its field-name pipeline, so we provide a three-column
    identity file.  No entries means no renames.
    """
    return "tiny\t2\t0\tofficial\tintermediary\tnamed\n"


def build_gradle(profile: GameProfile, modid: str, mod_version: str, java_release: str) -> str:
    loom = profile.fabric["loom_version"]
    loader = profile.fabric["loader_version"]
    api = profile.fabric["fabric_api_version"]
    game = profile.game_version
    return f"""\
plugins {{
    id("fabric-loom") version "{loom}"
}}

version = "{mod_version}"
group = "net.pymod.{normalize_java_identifier(modid)}"

base {{
    archivesName = "{modid}"
}}

repositories {{
    mavenCentral()
}}

dependencies {{
    minecraft("com.mojang:minecraft:{game}")
    // 26.x: Mojang ships a named (de-obfuscated) jar. Loom needs a mappings
    // layer with a 'named' column; the generated identity tiny (official ->
    // intermediary -> named, all identical) provides exactly that with zero
    // renames. Published yarn / mojang mappings don't exist for 26.2.
    mappings(loom.layered {{ mappings(file("mappings/identity.tiny")) }})
    modImplementation("net.fabricmc:fabric-loader:{loader}")
    modImplementation("net.fabricmc.fabric-api:fabric-api:{api}")
}}

java {{
    withSourcesJar()
}}

// Sources are already in Mojang names (identity mappings / named jar), so the
// sources-jar remap has nothing to do -- and the empty identity tree would fail it.
tasks.named("remapSourcesJar") {{
    enabled = false
}}

tasks.withType<JavaCompile>().configureEach {{
    options.release.set({java_release})
}}
"""


def fabric_mod_json(
    profile: GameProfile,
    modid: str,
    name: str,
    mod_version: str,
    description: str,
    entrypoint_class: str,
) -> str:
    loader = profile.fabric["loader_version"]
    game = profile.game_version
    doc = {
        "schemaVersion": 1,
        "id": modid,
        "version": mod_version,
        "name": name,
        "description": description,
        "environment": "*",
        "entrypoints": {"main": [entrypoint_class]},
        "depends": {
            "fabricloader": f">={loader}",
            "minecraft": f"~{game}.0",
            "java": ">=25",
        },
        "suggests": {"fabric-api": "*"},
    }
    return json.dumps(doc, indent=2, ensure_ascii=False)


def entrypoint_main(
    modid: str,
    mod_name: str,
    registrations: list[tuple[str, str, dict]],  # (kind, name, props)
) -> str:
    pkg = package_name(modid)
    cls = main_class_name(modid)
    lines: list[str] = []
    for kind, name, props in registrations:
        jname = json.dumps(name)
        ident = f"Identifier.fromNamespaceAndPath(MOD_ID, {jname})"
        if kind == "item":
            max_stack = props.get("max_stack", 64)
            lines.append(
                f"        Registry.register(BuiltInRegistries.ITEM, {ident}, "
                f"new Item(new Item.Properties().stacksTo({max_stack})));"
            )
        elif kind == "block":
            hardness = props.get("hardness", 3.0)
            lines.append(
                f"        Registry.register(BuiltInRegistries.BLOCK, {ident}, "
                f"new Block(BlockBehaviour.Properties.of().strength({hardness}f)));"
            )
    reg_body = "\n".join(lines) if lines else "        // no registrations"

    imports = [
        "import net.fabricmc.api.ModInitializer;",
        "import org.slf4j.Logger;",
        "import org.slf4j.LoggerFactory;",
    ]
    if lines:
        imports.append("import net.minecraft.core.Registry;")
        imports.append("import net.minecraft.core.registries.BuiltInRegistries;")
        imports.append("import net.minecraft.resources.Identifier;")
        imports.append("import net.minecraft.world.item.Item;")
        imports.append("import net.minecraft.world.level.block.Block;")
        imports.append("import net.minecraft.world.level.block.state.BlockBehaviour;")

    return f"""\
package {pkg};

{chr(10).join(sorted(imports))}

public class {cls} implements ModInitializer {{
    public static final String MOD_ID = "{modid}";
    public static final Logger LOGGER = LoggerFactory.getLogger(MOD_ID);

    @Override
    public void onInitialize() {{
{reg_body}
        LOGGER.info("{{}} initialized", MOD_ID);
    }}
}}
"""


