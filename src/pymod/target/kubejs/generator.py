"""KubeJS script generator (stage 4).

Emits a single ``server_scripts/<modid>.js`` that a KubeJS pack loads on the
server.  Every emitted line maps onto a real KubeJS API used in its canonical
shape -- nothing fabricated:

  * ``player.use_item``          -> ``ItemEvents.rightClicked(event => ...)``
  * ``player.right_click_block`` -> ``BlockEvents.rightClicked(event => ...)``
  * ``block.broken``             -> ``BlockEvents.broken(event => ...)``
  * ``send_message``             -> ``event.player.tell(msg)``
  * ``give_item``                -> ``event.player.give(Item.of(id, count))``
  * ``set_block``                -> ``event.server.runCommandSilent('setblock ...')``
  * tag registrations            -> ``ServerEvents.tags(event => event.add(...))``

The capability matrix in ``capability.py`` decides which events/actions reach
this file; anything else was already rejected by the checker.
"""
from __future__ import annotations

import json
from pathlib import Path

from ...errors import TargetError
from ...ir.irnodes import Guard, ModSpec
from ...registry.gameprofile import profile_for
from ..base import CodeTarget

# event kind -> KubeJS event-bus callback
_CALLBACK = {
    "player.use_item": "ItemEvents.rightClicked",
    "player.right_click_block": "BlockEvents.rightClicked",
    "block.broken": "BlockEvents.broken",
}

#: ctx parameter -> JS expression that resolves it inside the callback
_PARAM_EXPR = {
    "item": "event.item.id",
    "block": "event.block.id",
}


class KubeJSTarget(CodeTarget):
    name = "kubejs"

    def __init__(self, spec: ModSpec, out_dir: Path, game_version: str = "26.2") -> None:
        super().__init__(spec, out_dir)
        self.game_version = game_version
        self.profile = profile_for(game_version)

    # ------------------------------------------------------------------
    def generate(self) -> list[Path]:
        modid = self.spec.info.id
        parts: list[str] = [
            "// generated by pymod",
            f"// mod: {self.spec.info.name} ({self.spec.info.id} v{self.spec.info.version})",
            "",
        ]

        tag_regs = [r for r in self.spec.registrations if r.kind == "tag"]
        if tag_regs:
            parts.append("ServerEvents.tags((event) => {")
            for reg in tag_regs:
                values = ", ".join(f"'{v}'" for v in dict(reg.props).get("values", ()))
                tag_id = f"{modid}:{reg.name}"
                parts.append(f"  event.add('{tag_id}', [{values}]);")
            parts.append("});")
            parts.append("")

        item_regs = [r for r in self.spec.registrations if r.kind != "tag"]
        if item_regs:
            parts.append(
                "// item/block registrations are metadata in the KubeJS MVP "
                "(KubeJS cannot define new game content without assets)."
            )
            parts.append("")

        for handler in self.spec.events:
            parts.extend(self._emit_handler(handler))

        body = "\n".join(parts).rstrip() + "\n"
        return [self.write(f"server_scripts/{modid}.js", body)]

    # ------------------------------------------------------------------
    def _emit_handler(self, handler) -> list[str]:
        callback = _CALLBACK.get(handler.kind)
        if callback is None:
            raise TargetError(
                "target-unsupported-event",
                f"kubejs has no callback for event {handler.kind!r} (handler "
                f"{handler.handler_name!r})",
                loc=handler.loc,
            )

        lines = [f"// {handler.kind} ({handler.handler_name})", f"{callback}((event) => {{"]
        for guards, actions in self._group_runs(handler.body):
            if guards:
                cond = " && ".join(self._guard_js(g) for g in guards)
                lines.append(f"  if ({cond}) {{")
                for action in actions:
                    lines.extend(self._emit_action(action, "    "))
                lines.append("  }")
            else:
                for action in actions:
                    lines.extend(self._emit_action(action, "  "))
        lines.append("});")
        lines.append("")
        return lines

    @staticmethod
    def _group_runs(body):
        """Group consecutive actions with semantically identical guards.

        Guards carry a ``loc`` that differs per action, so equality is compared
        on a canonical (lhs_kind, lhs, op, rhs) key, not on the object.
        """
        runs: list[tuple] = []
        cur: tuple | None = None
        for action in body:
            key = tuple(
                sorted((g.lhs_kind, g.lhs, g.op, str(g.rhs)) for g in action.guards)
            )
            if key != cur:
                runs.append((action.guards, [action]))
                cur = key
            else:
                runs[-1][1].append(action)
        return runs

    def _guard_js(self, g: Guard) -> str:
        expr = _PARAM_EXPR.get(g.lhs) if g.lhs_kind == "param" else None
        if expr is None:
            raise TargetError(
                "kubejs-unsupported-guard",
                f"kubejs MVP supports ctx.item / ctx.block conditions only, "
                f"not ctx.{g.lhs} {g.op} {g.rhs}",
                loc=g.loc,
            )
        rhs = json.dumps(g.rhs) if isinstance(g.rhs, str) else str(g.rhs)
        js_op = {"==": "===", "!=": "!==", ">": ">", "<": "<", ">=": ">=", "<=": "<="}[g.op]
        return f"{expr} {js_op} {rhs}"

    def _emit_action(self, action, indent: str) -> list[str]:
        op, args = action.op, action.args
        pad = indent
        if op == "send_message":
            (msg,) = args
            return [f"{pad}event.player.tell({json.dumps(msg, ensure_ascii=False)});"]
        if op == "give_item":
            item = args[0]
            count = args[1] if len(args) > 1 else 1
            return [f"{pad}event.player.give(Item.of({json.dumps(item)}, {count}));"]
        if op == "set_block":
            x, y, z, block = args
            cmd = f"setblock {x} {y} {z} {block}"
            return [f"{pad}event.server.runCommandSilent({json.dumps(cmd)});"]
        raise TargetError(
            "target-unsupported-action",
            f"kubejs has no emission for ctx.{op}(...)",
            loc=action.loc,
        )